export const STATE_CODES = Object.values(STATE_NAMES);

export function normalizeState(value: string): string | null {
  const trimmed = value.trim();
  if (!trimmed) return null;
  if (/^[A-Za-z]{2}$/.test(trimmed)) {
    const code = trimmed.toUpperCase();
    return STATE_CODES.includes(code) ? code : null;
  }
  return STATE_NAMES[trimmed.toLowerCase().replace(/\./g, "").replace(/\s+/g, " ")] ?? null;
}
